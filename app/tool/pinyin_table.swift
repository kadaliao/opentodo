// Writes lib/domain/pinyin_table.dart: the toneless pinyin (ü as v) of every
// CJK Unified Ideograph U+4E00–U+9FFF, from macOS's Mandarin-to-Latin
// transform (ICU), one reading per character.
//
//   swift tool/pinyin_table.swift > lib/domain/pinyin_table.dart
let first = 0x4E00, last = 0x9FFF
let alphabet = Array("0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_")

func pinyin(_ s: String) -> String {
  let m = NSMutableString(string: s)
  CFStringTransform(m, nil, kCFStringTransformMandarinLatin, false)
  // Tone marks dropped; u with a diaeresis (ü) written v.
  var out = ""
  for u in (m as String).decomposedStringWithCanonicalMapping.unicodeScalars {
    if u.value == 0x308, out.last == "u" {
      out.removeLast(); out.append("v")
    } else if !(0x300...0x36F).contains(u.value) {
      out.unicodeScalars.append(u)
    }
  }
  out = out.lowercased()
  return out.allSatisfy({ $0 >= "a" && $0 <= "z" }) ? out : ""
}

